DROP POLICY IF EXISTS "Service write project interests" ON project_interests;
CREATE POLICY "Service write project interests" ON project_interests FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Service write project slots" ON project_availability_slots;
CREATE POLICY "Service write project slots" ON project_availability_slots FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Service write team members" ON team_members;
