-- 1. Create Core Database Tables
-- ------------------------------------------------------------------------------

-- Skills Catalog
CREATE TABLE IF NOT EXISTS skills (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT UNIQUE NOT NULL,
    category TEXT NOT NULL,
    active INTEGER DEFAULT 1
);

-- Interests Catalog
CREATE TABLE IF NOT EXISTS interests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT UNIQUE NOT NULL,
    category TEXT
);

-- User Profiles (mapped directly to Supabase Auth auth.users)
CREATE TABLE IF NOT EXISTS profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    email TEXT UNIQUE NOT NULL,
    display_name TEXT,
    usn TEXT,
    branch TEXT DEFAULT 'CSE',
    year TEXT DEFAULT '1st Year',
    section TEXT DEFAULT 'CSE-13',
    institution TEXT DEFAULT 'BMS Institute of Technology and Management',
    bio TEXT,
    github_url TEXT,
    linkedin_url TEXT,
    portfolio_url TEXT,
    role TEXT DEFAULT 'student', -- 'student', 'coordinator', 'admin'
    status TEXT DEFAULT 'active', -- 'active', 'deactivated'
    is_match_ready INTEGER DEFAULT 0,
    visibility TEXT DEFAULT 'cohort_only',
    show_contact_after_accept INTEGER DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Projects Table
CREATE TABLE IF NOT EXISTS projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id TEXT NOT NULL, -- references auth.users(id) UUID as text, or legacy student integer ID
    title TEXT NOT NULL,
    description TEXT,
    category TEXT DEFAULT 'Other',
    objectives TEXT,
    technologies TEXT,
    duration TEXT DEFAULT '2–3 Months',
    collaboration_mode TEXT DEFAULT 'Hybrid',
    availability TEXT DEFAULT 'Flexible',
    additional_requirements TEXT,
    course_context TEXT DEFAULT 'Innovation & Design Thinking (IDT)',
    team_size_min INTEGER DEFAULT 2,
    team_size_max INTEGER DEFAULT 4,
    schedule_notes TEXT,
    status TEXT DEFAULT 'draft', -- 'draft', 'published', 'closed'
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Project Skill Requirements
CREATE TABLE IF NOT EXISTS project_skill_requirements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    skill_id BIGINT NOT NULL REFERENCES skills(id) ON DELETE CASCADE,
    priority TEXT DEFAULT 'must-have',
    proficiency_level TEXT DEFAULT 'intermediate',
    weight DOUBLE PRECISION DEFAULT 3.0,
    required_count INTEGER DEFAULT 1,
    UNIQUE(project_id, skill_id)
);

-- Project Interests
CREATE TABLE IF NOT EXISTS project_interests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    interest_id BIGINT NOT NULL REFERENCES interests(id) ON DELETE CASCADE,
    UNIQUE(project_id, interest_id)
);

-- Project Availability Slots
CREATE TABLE IF NOT EXISTS project_availability_slots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    day_of_week TEXT NOT NULL,
    time_block TEXT NOT NULL,
    UNIQUE(project_id, day_of_week, time_block)
);

-- Team Members
CREATE TABLE IF NOT EXISTS team_members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    user_id TEXT NOT NULL,
    role TEXT DEFAULT 'member', -- 'owner', 'member', 'mentor'
    joined_at TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE(project_id, user_id)
);

-- Project Applications
CREATE TABLE IF NOT EXISTS project_applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    applicant_id TEXT NOT NULL,
    introduction TEXT,
    application_status TEXT DEFAULT 'pending', -- 'pending', 'accepted', 'rejected', 'withdrawn'
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE(project_id, applicant_id)
);

-- Project Invitations
CREATE TABLE IF NOT EXISTS invitations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    inviter_id TEXT NOT NULL,
    invitee_id TEXT NOT NULL,
    status TEXT DEFAULT 'pending', -- 'pending', 'accepted', 'declined', 'expired'
    message TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    responded_at TIMESTAMPTZ
);


-- ==============================================================================
-- 2. RBAC Helper Functions (Security Definer)
-- ==============================================================================

-- Determine if current session belongs to an Administrator or Faculty Coordinator
CREATE OR REPLACE FUNCTION public.is_admin(user_id UUID DEFAULT auth.uid())
RETURNS BOOLEAN
LANGUAGE sql
SECURITY DEFINER
STABLE
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.profiles
    WHERE id = user_id
      AND LOWER(role) IN ('admin', 'coordinator')
  );
$$;

-- Trigger to automatically create a profile record when a user signs up via Supabase Auth
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
  INSERT INTO public.profiles (id, email, display_name, role, status)
  VALUES (
    NEW.id,
    NEW.email,
    COALESCE(NEW.raw_user_meta_data->>'full_name', split_part(NEW.email, '@', 1)),
    COALESCE(NEW.raw_user_meta_data->>'role', 'student'),
    'active'
  )
  ON CONFLICT (id) DO NOTHING;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();


