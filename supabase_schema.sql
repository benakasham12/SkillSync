-- ------------------------------------------------------------------------------
-- A. PROFILES TABLE RLS POLICIES
-- ------------------------------------------------------------------------------

-- 1. SELECT: All authenticated users and public visitors can view profiles
DROP POLICY IF EXISTS "Profiles are readable by authenticated users and visitors" ON profiles;
CREATE POLICY "Profiles are readable by authenticated users and visitors"
  ON profiles FOR SELECT
  USING (true);

-- 2. INSERT: Users can create their own profile (or admins can create any)
DROP POLICY IF EXISTS "Users can insert their own profile" ON profiles;
CREATE POLICY "Users can insert their own profile"
  ON profiles FOR INSERT
  WITH CHECK (
    auth.uid() = id
    OR public.is_admin(auth.uid())
    OR auth.role() = 'service_role'
  );

-- 3. UPDATE: Users can update their own profile; admins can update ANY profile
DROP POLICY IF EXISTS "Users update own profile or admins update any" ON profiles;
CREATE POLICY "Users update own profile or admins update any"
  ON profiles FOR UPDATE
  USING (
    auth.uid() = id
    OR public.is_admin(auth.uid())
    OR auth.role() = 'service_role'
  )
  WITH CHECK (
    auth.uid() = id
    OR public.is_admin(auth.uid())
    OR auth.role() = 'service_role'
  );

-- 4. DELETE: Only admins can delete profiles (and service role)
DROP POLICY IF EXISTS "Only admins can delete profiles" ON profiles;
CREATE POLICY "Only admins can delete profiles"
  ON profiles FOR DELETE
  USING (
    public.is_admin(auth.uid())
    OR auth.role() = 'service_role'
  );


-- ------------------------------------------------------------------------------
-- B. PROJECTS TABLE RLS POLICIES
-- ------------------------------------------------------------------------------

-- 1. SELECT: All users can view published/closed projects; admins can view all (including drafts)
DROP POLICY IF EXISTS "Public and users can view published projects; admins view all" ON projects;
CREATE POLICY "Public and users can view published projects; admins view all"
  ON projects FOR SELECT
  USING (
    status IN ('published', 'closed')
    OR owner_id = auth.uid()::text
    OR public.is_admin(auth.uid())
    OR auth.role() = 'service_role'
  );

-- 2. INSERT: Authenticated users can create projects
DROP POLICY IF EXISTS "Authenticated users can create projects" ON projects;
CREATE POLICY "Authenticated users can create projects"
  ON projects FOR INSERT
  WITH CHECK (
    auth.uid() IS NOT NULL
    OR auth.role() = 'service_role'
  );

-- 3. UPDATE: Creator can update their own project; admins can update ANY project
DROP POLICY IF EXISTS "Creators or admins can update projects" ON projects;
CREATE POLICY "Creators or admins can update projects"
  ON projects FOR UPDATE
  USING (
    owner_id = auth.uid()::text
    OR public.is_admin(auth.uid())
    OR auth.role() = 'service_role'
  )
  WITH CHECK (
    owner_id = auth.uid()::text
    OR public.is_admin(auth.uid())
    OR auth.role() = 'service_role'
  );

-- 4. DELETE: Creator can delete their own project; admins can delete ANY project; service role permitted
DROP POLICY IF EXISTS "Creators or admins can delete projects" ON projects;
CREATE POLICY "Creators or admins can delete projects"
  ON projects FOR DELETE
  USING (
    owner_id = auth.uid()::text
    OR public.is_admin(auth.uid())
    OR auth.role() = 'service_role'
  );


-- ------------------------------------------------------------------------------
-- C. CATALOGS & DEPENDENT TABLES RLS POLICIES
-- ------------------------------------------------------------------------------

